// BCP 47 arrives as en-GB or zh-Hant-TW; Wallos names the same languages with
// underscores and its own regional spellings, and the picker shows those codes,
// so the header is mapped onto them rather than the other way round.
export function pickLocale(acceptLanguage: string | null, override?: string | null): string {
	if (override && KNOWN.has(override)) return override;
	if (!acceptLanguage) return "en";
	const ranked = acceptLanguage
		.split(",")
		.map((part) => {
			const [tag = "", ...params] = part.trim().split(";");
			const q = params.find((p) => p.startsWith("q="));
			return { tag: tag.toLowerCase(), q: q ? Number(q.slice(2)) || 0 : 1 };
		})
		.filter((entry) => entry.tag)
		.sort((a, b) => b.q - a.q);
	for (const { tag } of ranked) {
		const direct = tag.replace("-", "_");
		if (KNOWN.has(direct)) return direct;
		const [base = "", region = ""] = tag.split("-");
		if (base === "zh") {
			if (["tw", "hk", "mo", "hant"].includes(region)) return "zh_tw";
			return "zh_cn";
		}
		if (base === "pt") return region === "br" ? "pt_br" : "pt";
		if (KNOWN.has(base)) return base;
	}
	return "en";
}
